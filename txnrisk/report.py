"""Writes the Markdown report, charts and Power BI-ready CSV marts."""
from __future__ import annotations

from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import pandas as pd  # noqa: E402


def md_table(df: pd.DataFrame, floatfmt: str = "{:,.4f}") -> str:
    def fmt(v):
        if isinstance(v, float):
            return floatfmt.format(v) if abs(v) < 1000 else f"{v:,.0f}"
        if isinstance(v, int):
            return f"{v:,}"
        return str(v)

    head = "| " + " | ".join(map(str, df.columns)) + " |"
    sep = "| " + " | ".join("---" for _ in df.columns) + " |"
    body = ["| " + " | ".join(fmt(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join([head, sep, *body])


def _charts(out: Path, training: dict, scorecard: pd.DataFrame, mi: dict[str, pd.DataFrame]) -> None:
    fig, ax = plt.subplots(figsize=(6, 4.5))
    for r in training["results"].values():
        precision, recall = r.pr_curve
        ax.plot(recall, precision, label=f"{r.name} (PR-AUC {r.metrics['pr_auc']:.3f})")
    ax.axhline(1 - training["baseline_accuracy"], ls="--", c="grey", label="random (fraud rate)")
    ax.set(xlabel="Recall", ylabel="Precision", title="Precision-recall curve (test window)")
    ax.legend(loc="lower left", fontsize=8)
    fig.tight_layout(); fig.savefig(out / "pr_curve.png", dpi=130); plt.close(fig)

    hourly = mi["fraud_by_hour"]
    fig, ax = plt.subplots(figsize=(7, 3.5))
    ax.bar(hourly["hour"], hourly["fraud_rate_pct"], color="#c0392b")
    ax.set(xlabel="Hour of day", ylabel="Fraud rate (%)", title="Fraud rate by hour")
    fig.tight_layout(); fig.savefig(out / "fraud_by_hour.png", dpi=130); plt.close(fig)

    fig, ax = plt.subplots(figsize=(7, 3.8))
    colors = ["#c0392b" if s == "FAIL" else "#27ae60" for s in scorecard["status"]]
    ax.barh(scorecard["rule"], scorecard["failed_rows"], color=colors)
    ax.invert_yaxis()
    ax.set(xlabel="Failed rows", title="Data-quality scorecard (red = below threshold)")
    fig.tight_layout(); fig.savefig(out / "dq_scorecard.png", dpi=130); plt.close(fig)

    top = training["importance"].head(10).iloc[::-1]
    fig, ax = plt.subplots(figsize=(7, 4))
    ax.barh(top["feature"], top["importance"], color="#2c3e50")
    ax.set(xlabel="Drop in PR-AUC when shuffled", title=f"Top features ({training['champion'].name})")
    fig.tight_layout(); fig.savefig(out / "feature_importance.png", dpi=130); plt.close(fig)


def write_report(out_dir: str | Path, *, volumes: dict, defects: pd.DataFrame, scorecard: pd.DataFrame,
                 recon: dict, training: dict, mi: dict[str, pd.DataFrame]) -> Path:
    out = Path(out_dir)
    marts = out / "marts"
    marts.mkdir(parents=True, exist_ok=True)
    _charts(out, training, scorecard, mi)
    for name, df in mi.items():
        df.to_csv(marts / f"{name}.csv", index=False)
    scorecard.to_csv(marts / "dq_scorecard.csv", index=False)

    comparison = pd.DataFrame([{
        "model": r.name, "PR-AUC": r.metrics["pr_auc"], "ROC-AUC": r.metrics["roc_auc"],
        "precision": r.metrics["precision"], "recall": r.metrics["recall"], "F1": r.metrics["f1"],
        "alerts/day": r.metrics["alerts_per_day"], "fraud value caught %": r.metrics["fraud_value_caught_pct"],
    } for r in training["results"].values()])
    comparison.to_csv(marts / "model_comparison.csv", index=False)

    champ = training["champion"]
    m = champ.metrics
    split = training["split"]
    lines = [
        "# Transaction Risk Analytics - Run Report",
        "",
        "_Generated by `python -m txnrisk`. All data is synthetic._",
        "",
        "## 1. Data volumes",
        "",
        md_table(pd.DataFrame([volumes])),
        "",
        "## 2. Data quality",
        "",
        "Defects injected by the generator (ground truth):",
        "",
        md_table(defects),
        "",
        "Scorecard from the rule engine:",
        "",
        md_table(scorecard[["rule", "dimension", "failed_rows", "pass_rate", "threshold", "status"]], "{:.6f}"),
        "",
        "![DQ scorecard](dq_scorecard.png)",
        "",
        "Reconciliation (staged = promoted + quarantined):",
        "",
        md_table(pd.DataFrame([recon]), "{:,.2f}"),
        "",
        "## 3. Fraud model",
        "",
        f"Time-based split - train {split['train_rows']:,} rows ({split['train_fraud']} fraud), "
        f"validation {split['valid_rows']:,} ({split['valid_fraud']} fraud), "
        f"test {split['test_rows']:,} ({split['test_fraud']} fraud), test period {split['test_period']}.",
        "",
        md_table(comparison),
        "",
        f"**Champion: `{champ.name}`** at alert threshold {champ.threshold:.3f} (tuned on validation): "
        f"precision {m['precision']:.1%}, recall {m['recall']:.1%}, "
        f"{m['fraud_value_caught_pct']:.1f}% of fraud value caught, {m['alerts_per_day']:.1f} alerts/day.",
        "",
        f"Confusion matrix on test: TP {m['tp']}, FP {m['fp']}, FN {m['fn']}, TN {m['tn']:,}.",
        "",
        f"Why not accuracy? A model that flags nothing scores **{training['baseline_accuracy']:.2%}** accuracy "
        f"on the test window while catching zero fraud. The champion's accuracy is {m['accuracy']:.2%} - "
        "almost the same number, which is exactly why it is the wrong metric here.",
        "",
        "![PR curve](pr_curve.png)",
        "",
        "![Feature importance](feature_importance.png)",
        "",
        "## 4. Business MI",
        "",
    ]
    for name, df in mi.items():
        if name == "fraud_by_hour":
            lines += [f"### {name}", "", "![Fraud by hour](fraud_by_hour.png)", ""]
        else:
            lines += [f"### {name}", "", md_table(df, "{:,.3f}"), ""]
    path = out / "report.md"
    path.write_text("\n".join(lines))
    return path
